-- =====================================================================
-- BANKDOIT · 01_esquema.sql
-- Tablas, llaves y restricciones. Issue #16 (diseño base en #3).
--
-- Convenciones acordadas con la API (docs/api-bankroll.md):
--   * Montos en pesos con dos decimales -> NUMERIC, nunca FLOAT.
--   * Estados de apuesta: pendiente, ganada, perdida, anulada.
--   * Cuota decimal mayor a 1.
--   * La clave de idempotencia (encabezado Idempotency-Key) es texto
--     ASCII imprimible de 1 a 128 caracteres, única por usuario.
--
-- Todas las tablas con datos personales llevan usuario_id (shard key),
-- para que en #17 cada fragmento contenga completo lo de sus usuarios.
-- =====================================================================

-- ---------------------------------------------------------------------
-- Catálogo común (se replica igual en ambos fragmentos)
-- ---------------------------------------------------------------------

CREATE TABLE deporte (
    deporte_id  SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      VARCHAR(40) NOT NULL,
    CONSTRAINT uq_deporte_nombre UNIQUE (nombre),
    CONSTRAINT ck_deporte_nombre CHECK (btrim(nombre) <> '')
);

CREATE TABLE equipo (
    equipo_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    deporte_id  SMALLINT NOT NULL REFERENCES deporte (deporte_id),
    nombre      VARCHAR(100) NOT NULL,
    CONSTRAINT uq_equipo_nombre UNIQUE (deporte_id, nombre),
    -- Permite que partido exija que ambos equipos sean del mismo deporte.
    CONSTRAINT uq_equipo_deporte UNIQUE (equipo_id, deporte_id),
    CONSTRAINT ck_equipo_nombre CHECK (btrim(nombre) <> '')
);

CREATE TABLE partido (
    partido_id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    deporte_id           SMALLINT NOT NULL REFERENCES deporte (deporte_id),
    equipo_local_id      BIGINT NOT NULL,
    equipo_visitante_id  BIGINT NOT NULL,
    fecha_hora           TIMESTAMPTZ NOT NULL,
    estado               VARCHAR(12) NOT NULL DEFAULT 'programado',
    CONSTRAINT fk_partido_local
        FOREIGN KEY (equipo_local_id, deporte_id) REFERENCES equipo (equipo_id, deporte_id),
    CONSTRAINT fk_partido_visitante
        FOREIGN KEY (equipo_visitante_id, deporte_id) REFERENCES equipo (equipo_id, deporte_id),
    CONSTRAINT ck_partido_equipos CHECK (equipo_local_id <> equipo_visitante_id),
    CONSTRAINT ck_partido_estado CHECK (estado IN ('programado', 'finalizado', 'cancelado')),
    CONSTRAINT uq_partido UNIQUE (equipo_local_id, equipo_visitante_id, fecha_hora)
);

-- ---------------------------------------------------------------------
-- Datos del usuario (se fragmentan por usuario_id)
-- ---------------------------------------------------------------------

CREATE TABLE usuario (
    usuario_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alias            VARCHAR(40) NOT NULL,
    hash_contrasena  TEXT NOT NULL,          -- lo genera la API (bcrypt/argon2); nunca texto plano
    rol              VARCHAR(13) NOT NULL DEFAULT 'usuario',
    estado           VARCHAR(10) NOT NULL DEFAULT 'activo',
    creado_en        TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_usuario_alias UNIQUE (alias),
    CONSTRAINT ck_usuario_alias CHECK (alias ~ '^[A-Za-z0-9_.-]{3,40}$'),
    CONSTRAINT ck_usuario_hash CHECK (length(hash_contrasena) >= 20),
    CONSTRAINT ck_usuario_rol CHECK (rol IN ('usuario', 'administrador')),
    CONSTRAINT ck_usuario_estado CHECK (estado IN ('activo', 'suspendido'))
);

-- Un solo bankroll por usuario: la llave primaria ES el usuario_id.
-- saldo_disponible y monto_en_juego solo los modifica el trigger de
-- movimiento (ver 02_funciones_triggers.sql); el historial de
-- movimientos es la fuente auditable.
CREATE TABLE bankroll (
    usuario_id        BIGINT PRIMARY KEY REFERENCES usuario (usuario_id),
    saldo_disponible  NUMERIC(12,2) NOT NULL DEFAULT 0,
    monto_en_juego    NUMERIC(12,2) NOT NULL DEFAULT 0,
    limite_semanal    NUMERIC(12,2),          -- NULL = sin límite
    actualizado_en    TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_bankroll_disponible CHECK (saldo_disponible >= 0),
    CONSTRAINT ck_bankroll_en_juego CHECK (monto_en_juego >= 0),
    CONSTRAINT ck_bankroll_limite CHECK (limite_semanal IS NULL OR limite_semanal > 0)
);

CREATE TABLE apuesta (
    apuesta_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id       BIGINT NOT NULL REFERENCES bankroll (usuario_id),
    partido_id       BIGINT NOT NULL REFERENCES partido (partido_id),
    clave_operacion  VARCHAR(128) NOT NULL,
    seleccion        VARCHAR(180) NOT NULL,
    monto            NUMERIC(10,2) NOT NULL,
    cuota            NUMERIC(6,2) NOT NULL,
    estado           VARCHAR(9) NOT NULL DEFAULT 'pendiente',
    origen           VARCHAR(60),             -- etiqueta libre: "App A", etc.
    registrada_en    TIMESTAMPTZ NOT NULL DEFAULT now(),
    resuelta_en      TIMESTAMPTZ,
    CONSTRAINT uq_apuesta_clave UNIQUE (usuario_id, clave_operacion),
    -- Destino de las llaves foráneas compuestas de movimiento y recuerdo:
    -- garantiza que el movimiento/recuerdo sea del mismo dueño que la apuesta.
    CONSTRAINT uq_apuesta_usuario UNIQUE (apuesta_id, usuario_id),
    CONSTRAINT ck_apuesta_clave CHECK (clave_operacion ~ '^[!-~]{1,128}$'),
    CONSTRAINT ck_apuesta_seleccion CHECK (btrim(seleccion) <> ''),
    CONSTRAINT ck_apuesta_monto CHECK (monto > 0),
    CONSTRAINT ck_apuesta_cuota CHECK (cuota > 1),
    CONSTRAINT ck_apuesta_estado CHECK (estado IN ('pendiente', 'ganada', 'perdida', 'anulada')),
    CONSTRAINT ck_apuesta_resolucion CHECK ((estado = 'pendiente') = (resuelta_en IS NULL)),
    CONSTRAINT ck_apuesta_origen CHECK (origen IS NULL OR btrim(origen) <> '')
);

-- Cada cambio del bankroll queda como un movimiento inmutable.
-- cambio_disponible / cambio_en_juego son con signo; la suma de todos
-- los movimientos de un usuario debe coincidir con su bankroll.
CREATE TABLE movimiento (
    movimiento_id      BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    usuario_id         BIGINT NOT NULL REFERENCES bankroll (usuario_id),
    apuesta_id         BIGINT,
    tipo               VARCHAR(13) NOT NULL,
    cambio_disponible  NUMERIC(12,2) NOT NULL,
    cambio_en_juego    NUMERIC(12,2) NOT NULL,
    creado_en          TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_movimiento_apuesta
        FOREIGN KEY (apuesta_id, usuario_id) REFERENCES apuesta (apuesta_id, usuario_id),
    -- Una sola reserva y una sola liquidación por apuesta: impide el doble cargo.
    CONSTRAINT uq_movimiento_apuesta_tipo UNIQUE (apuesta_id, tipo),
    CONSTRAINT ck_movimiento_tipo CHECK (tipo IN
        ('saldo_inicial', 'aportacion', 'retiro', 'reserva', 'liquidacion')),
    -- Forma válida de cada tipo de movimiento.
    CONSTRAINT ck_movimiento_forma CHECK (
        CASE tipo
            WHEN 'saldo_inicial' THEN apuesta_id IS NULL AND cambio_disponible >= 0 AND cambio_en_juego = 0
            WHEN 'aportacion'    THEN apuesta_id IS NULL AND cambio_disponible > 0  AND cambio_en_juego = 0
            WHEN 'retiro'        THEN apuesta_id IS NULL AND cambio_disponible < 0  AND cambio_en_juego = 0
            WHEN 'reserva'       THEN apuesta_id IS NOT NULL AND cambio_disponible < 0
                                      AND cambio_en_juego = -cambio_disponible
            WHEN 'liquidacion'   THEN apuesta_id IS NOT NULL AND cambio_disponible >= 0
                                      AND cambio_en_juego < 0
        END
    )
);

-- Fotografía opcional de una apuesta. Solo se guarda la referencia
-- privada al archivo; la API valida que quien lo pide sea el dueño.
CREATE TABLE recuerdo (
    recuerdo_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id    BIGINT NOT NULL,
    apuesta_id    BIGINT NOT NULL,
    ruta_objeto   VARCHAR(500) NOT NULL,
    tipo_mime     VARCHAR(20) NOT NULL,
    tamano_bytes  INTEGER NOT NULL,
    creado_en     TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_recuerdo_apuesta
        FOREIGN KEY (apuesta_id, usuario_id) REFERENCES apuesta (apuesta_id, usuario_id),
    CONSTRAINT uq_recuerdo_ruta UNIQUE (ruta_objeto),
    CONSTRAINT ck_recuerdo_mime CHECK (tipo_mime IN ('image/jpeg', 'image/png', 'image/webp')),
    CONSTRAINT ck_recuerdo_tamano CHECK (tamano_bytes BETWEEN 1 AND 10485760)  -- máx. 10 MB
);

-- ---------------------------------------------------------------------
-- Índices para los patrones de acceso más frecuentes
-- ---------------------------------------------------------------------

-- "Mis apuestas": por usuario, filtradas por estado y ordenadas por fecha.
CREATE INDEX ix_apuesta_usuario_estado ON apuesta (usuario_id, estado, registrada_en DESC);
-- Estadísticas globales por partido.
CREATE INDEX ix_apuesta_partido ON apuesta (partido_id, estado);
-- Historial de movimientos del bankroll.
CREATE INDEX ix_movimiento_usuario_fecha ON movimiento (usuario_id, creado_en DESC);
CREATE INDEX ix_recuerdo_apuesta ON recuerdo (apuesta_id);
-- Búsqueda de partidos de una jornada.
CREATE INDEX ix_partido_fecha ON partido (deporte_id, fecha_hora);
